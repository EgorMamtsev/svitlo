export const adaptCherkasy = (
  oeData: OEData,
  regionName: string
): AdaptedOESchedule => {
  // Доповнюємо дані preset, якщо його немає
  const fullData: OEData = {
    ...oeData,
    preset: oeData.preset || {
      time_zone: DEFAULT_TIME_ZONE,
      time_type: DEFAULT_TIME_TYPE,
    },
  };

  return adaptOEBase(fullData, regionName);
};